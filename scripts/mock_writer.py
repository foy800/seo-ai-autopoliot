"""Заглушка вместо OpenAI: проверка конвейера без ключа и без сети."""
import os
import re


class MockWriter:
    def write(self, system, user):
        if user.startswith("Отредактируй статью"):
            return user.split("\n\n", 1)[1]  # вычитка: вернуть черновик как есть
        if user.startswith("Придумай заголовок"):
            k = re.search(r"Ключ: (.+)", user).group(1).strip()
            return k[:1].upper() + k[1:] + ": что важно знать"
        kw = re.search(r"Основной ключ: (.+)", user).group(1).strip()
        h1 = re.search(r"Заголовок H1 \(одобрен[^)]*\): (.+)", user).group(1).strip()
        sec = [x.strip() for x in re.search(r"Дополнительные ключи: (.+)", user).group(1).split(",")]
        lsi = [x.strip() for x in re.search(r"LSI-слова[^:]*: (.+)", user).group(1).split(",")]
        s1 = sec[0] if sec else "детали"
        s2 = sec[1] if len(sec) > 1 else s1
        l1, l2, l3 = (lsi + ["требования", "сроки", "документы"])[:3]
        cta_line = re.search(r"финального CTA: (.+)", user).group(1)
        cta, cta_title, cta_desc = [x.strip() for x in cta_line.split(" | ", 2)]
        block = user.split("Страницы для внутренних ссылок")[1]
        urls = re.findall(r"^- (\S+) \|", block, re.M)
        a = urls[0] if urls else "/"
        b = urls[1] if len(urls) > 1 else a
        K = kw.capitalize()
        desc = (f"Разбор темы: {kw}. Что входит, какие бывают варианты, сколько это занимает "
                "и на что обратить внимание при выборе. Коротко и по делу, с таблицей сроков.")
        return (
            f"META_TITLE: {K}: что важно знать\n"
            f"META_DESCRIPTION: {desc}\n"
            "IMAGE_SCENE: светлый офис с документами на столе\n"
            "IMAGE_ALT: рабочий стол с документами\n---\n"
            f"# {h1}\n\n"
            f"Тема «{kw}» вызывает много вопросов. "
            "Общий порядок понятен, но детали зависят от конкретного случая. "
            "Ниже разобраны варианты, сроки и типичные ошибки.\n\n"
            f"## Что это такое и {s1}\n\n"
            f"Процедура состоит из нескольких этапов. Про {s1} специалист говорит на старте, "
            f"потому что итог зависит от исходных данных: {l1}, {l2} и {l3} уточняют заранее. "
            "Одни случаи закрываются за один этап. Другие требуют подготовки, и тогда срок "
            f"растягивается на несколько недель. Подробнее в [разделе об услугах]({a}).\n\n"
            "**Важно!** Требования могут отличаться в зависимости от вида продукции или задачи.\n\n"
            "## Сравнение вариантов\n\n"
            "| Вариант | Срок | Когда подходит |\n|---|---|---|\n"
            "| Первый | 3 дня | Типовые случаи |\n"
            "| Второй | 10 дней | Нестандартные случаи |\n\n"
            "Таблица показывает общий порядок. Точный вариант выбирают после уточнения деталей. "
            f"Смежные темы описаны в [другом материале]({b}).\n\n"
            "## Как проходит работа\n\n"
            "Работа состоит из нескольких шагов:\n\n"
            "1. Специалист собирает исходные данные и уточняет задачу.\n"
            "2. Затем готовится план и список необходимых материалов.\n"
            "3. После согласования выполняется основная часть работы.\n\n"
            "Вопросы лучше задавать в начале, в конце их обычно забывают. Если что-то непонятно, "
            "специалист объясняет простыми словами. План фиксируют письменно, чтобы к нему можно было "
            "вернуться. Спешка на этом этапе обычно дороже, чем лишний день на подготовку.\n\n"
            "## Частые вопросы\n\n"
            "- Сколько это занимает: срок определяют сложность задачи и полнота исходных данных.\n"
            "- От чего зависит цена: от объёма работы и требований, поэтому без деталей её не называют.\n"
            "- Что подготовить заранее: список вопросов и документы, которые уже есть.\n\n"
            "**Обратите внимание!** Одинаковой цены для всех случаев не бывает.\n\n"
            f"## Что учесть про {s2}\n\n"
            "Есть ограничения: например, неполный комплект данных или нестандартные условия. "
            "Поэтому сначала уточнение, затем план. Перед началом стоит собрать вопросы и список "
            "имеющихся документов. Так работа проходит быстрее и точнее.\n\n"
            "**Дополнительная информация:** полезно заранее собрать примеры похожих задач, если они есть.\n\n"
            "## Вывод\n\n"
            "Результат зависит от исходных данных и определяется после уточнения задачи. "
            "Точный план и сроки называют только после обсуждения деталей.\n\n"
            f"Услуга «{cta_title}»: {cta_desc[:1].lower() + cta_desc[1:]}. "
            f"Запишитесь на [консультацию по услуге]({cta}), чтобы обсудить ваш случай.\n"
        )

    def image(self, scene, out):
        os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
        with open(out, "wb") as f:
            f.write(b"MOCK-IMAGE")
        return out
